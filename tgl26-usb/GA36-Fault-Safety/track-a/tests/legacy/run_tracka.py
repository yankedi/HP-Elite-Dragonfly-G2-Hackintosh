#!/usr/bin/env python3
"""GA36 Track A (legacy writer) harness generator and runner.

The two callback bodies are extracted verbatim from the frozen baseline/candidate
sources; only a fake XNU/vfs/uio layer and the scenario driver are ours. All paths
are derived from this file, so the runner is independent of the caller's CWD.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
TRACK_A = HERE.parent.parent
BASELINE = TRACK_A / "baseline" / "kern_igfx.cpp"
CANDIDATE = TRACK_A / "candidate" / "kern_igfx.cpp"
BUILD = HERE / "build"
LOGS = TRACK_A / "logs" / "legacy"

RECORDS_SIGNATURE = (
    "int IGFX::TigerLakeRegisterMap::hangWriteRecords(const void *data, size_t length) {"
)
THREAD_SIGNATURE = (
    "void IGFX::TigerLakeRegisterMap::hangThread(thread_call_param_t param0, "
    "thread_call_param_t) {"
)

MARK_BEGIN = "TRACKA_JSON_BEGIN"
MARK_END = "TRACKA_JSON_END"


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def extract_function(text: str, signature: str) -> str:
    """Return the exact source slice from `signature` through its matching brace.

    A small lexer skips comments and string/char literals so braces inside those
    do not affect nesting. The returned text is not rewritten.
    """
    start = text.find(signature)
    if start < 0:
        raise RuntimeError(f"signature not found: {signature}")
    # The signatures above already end in '{'; search from that final character
    # so the function brace, not its first nested block, starts the count.
    brace = text.find("{", start + len(signature) - 1)
    if brace < 0:
        raise RuntimeError(f"opening brace not found: {signature}")
    depth = 0
    index = brace
    state = "code"
    while index < len(text):
        char = text[index]
        nxt = text[index + 1] if index + 1 < len(text) else ""
        if state == "code":
            if char == "/" and nxt == "/":
                state = "line"
                index += 2
                continue
            if char == "/" and nxt == "*":
                state = "block"
                index += 2
                continue
            if char == '"':
                state = "string"
            elif char == "'":
                state = "char"
            elif char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    return text[start:index + 1]
        elif state == "line":
            if char == "\n":
                state = "code"
        elif state == "block":
            if char == "*" and nxt == "/":
                state = "code"
                index += 2
                continue
        elif state == "string":
            if char == "\\":
                index += 2
                continue
            if char == '"':
                state = "code"
        elif state == "char":
            if char == "\\":
                index += 2
                continue
            if char == "'":
                state = "code"
        index += 1
    raise RuntimeError(f"unterminated function: {signature}")


def find_gxx() -> Path | None:
    candidate = shutil.which("g++")
    if candidate:
        return Path(candidate)
    wrappers = sorted(Path("/nix/store").glob("*gcc-wrapper*/bin/g++"))
    if not wrappers:
        return None
    # Prefer the newest-looking wrapper name; any working g++ is acceptable.
    return sorted(wrappers, key=lambda path: path.parent.parent.name)[-1]


def compiler_version(binary: Path) -> str:
    try:
        result = subprocess.run(
            [str(binary), "--version"], capture_output=True, text=True, timeout=20
        )
        return result.stdout.splitlines()[0].strip()
    except Exception as exc:  # pragma: no cover - diagnostic only
        return f"version unavailable: {exc}"


def render_harness(impl: str, extracted: dict[str, str]) -> str:
    if impl == "baseline":
        define = '#define IMPL_NAME "baseline"\n#define IMPL_BASELINE 1\n'
    else:
        define = '#define IMPL_NAME "candidate"\n'
    return (
        "// Generated by run_tracka.py. Do not edit: the callback bodies are extracted.\n"
        + define
        + '#include "harness_prelude.hpp"\n\n'
        + "// ---- extracted verbatim from "
        + str(BASELINE if impl == "baseline" else CANDIDATE)
        + " ----\n"
        + extracted["hangWriteRecords"]
        + "\n\n"
        + extracted["hangThread"]
        + "\n\n"
        + "// ---- scenario driver (mock-only) ----\n"
        + '#include "harness_tests.inc"\n'
    )


def parse_harness_output(stdout: str) -> dict:
    if MARK_BEGIN not in stdout or MARK_END not in stdout:
        raise RuntimeError("harness did not emit markers")
    payload = stdout.split(MARK_BEGIN, 1)[1].split(MARK_END, 1)[0].strip()
    return json.loads(payload)


def main() -> int:
    BUILD.mkdir(parents=True, exist_ok=True)
    LOGS.mkdir(parents=True, exist_ok=True)

    baseline_text = BASELINE.read_text()
    candidate_text = CANDIDATE.read_text()
    baseline_functions = {
        "hangWriteRecords": extract_function(baseline_text, RECORDS_SIGNATURE),
        "hangThread": extract_function(baseline_text, THREAD_SIGNATURE),
    }
    candidate_functions = {
        "hangWriteRecords": extract_function(candidate_text, RECORDS_SIGNATURE),
        "hangThread": extract_function(candidate_text, THREAD_SIGNATURE),
    }

    provenance = {
        "baseline_file": str(BASELINE),
        "baseline_sha256": sha256_file(BASELINE),
        "candidate_file": str(CANDIDATE),
        "candidate_sha256": sha256_file(CANDIDATE),
        "extracted": {
            "baseline": {name: sha256_text(body) for name, body in baseline_functions.items()},
            "candidate": {name: sha256_text(body) for name, body in candidate_functions.items()},
        },
        "extraction": "verbatim brace-balanced slices; no algorithm rewriting",
    }

    generated = {}
    for impl, functions in (("baseline", baseline_functions), ("candidate", candidate_functions)):
        source = render_harness(impl, functions)
        source_path = BUILD / f"harness_{impl}.cpp"
        source_path.write_text(source)
        generated[impl] = source_path

    clang = shutil.which("clang++")
    gcc = find_gxx()
    compilers = []
    if clang:
        compilers.append(("clang", Path(clang)))
    if gcc:
        compilers.append(("gcc", gcc))
    if not compilers:
        print("no C++ compiler found", file=sys.stderr)
        return 2

    variants = [
        ("release", []),
        (
            "asan+ubsan",
            ["-fsanitize=address,undefined", "-fno-omit-frame-pointer", "-fno-sanitize-recover=all"],
        ),
    ]

    runs = []
    for impl in ("baseline", "candidate"):
        source_path = generated[impl]
        for compiler_name, compiler_path in compilers:
            for variant_name, sanitizer_flags in variants:
                label = f"{impl}-{compiler_name}-{variant_name}"
                binary = BUILD / f"tracka-{label}"
                compile_cmd = [
                    str(compiler_path),
                    "-std=c++17",
                    "-O2",
                    "-g",
                    "-pthread",
                    "-Wall",
                    "-Wextra",
                    "-Wno-unused-parameter",
                    f"-I{HERE}",
                    f'-DCOMPILER_NAME="{compiler_name}"',
                    f'-DSANITIZER_NAME="{variant_name}"',
                    *sanitizer_flags,
                    str(source_path),
                    "-o",
                    str(binary),
                ]
                build_log = LOGS / f"tracka-{label}.build.log"
                run_log = LOGS / f"tracka-{label}.run.log"
                compile_result = subprocess.run(
                    compile_cmd, capture_output=True, text=True, timeout=180
                )
                build_log.write_text(
                    "COMMAND: " + " ".join(compile_cmd) + "\n\n"
                    + compile_result.stdout
                    + compile_result.stderr
                )
                record = {
                    "impl": impl,
                    "compiler": compiler_name,
                    "compiler_version": compiler_version(compiler_path),
                    "variant": variant_name,
                    "source": str(source_path),
                    "binary": str(binary),
                    "build_log": str(build_log),
                    "run_log": str(run_log),
                    "compile_returncode": compile_result.returncode,
                }
                if compile_result.returncode != 0:
                    record.update({"ran": False, "pass": False, "reason": "compile failed"})
                    runs.append(record)
                    continue

                env = os.environ.copy()
                env["ASAN_OPTIONS"] = "detect_leaks=0:abort_on_error=1"
                env["UBSAN_OPTIONS"] = "halt_on_error=1:print_stacktrace=1"
                try:
                    run_result = subprocess.run(
                        [str(binary)],
                        cwd=str(BUILD),
                        capture_output=True,
                        text=True,
                        timeout=120,
                        env=env,
                    )
                    run_log.write_text(
                        "COMMAND: " + str(binary) + "\n\n"
                        + run_result.stdout
                        + run_result.stderr
                    )
                    record["returncode"] = run_result.returncode
                    try:
                        report = parse_harness_output(run_result.stdout)
                        record["report"] = report
                        record["pass"] = bool(report.get("failed", 1) == 0)
                    except Exception as exc:
                        record.update({"pass": False, "reason": f"output parse failed: {exc}"})
                except subprocess.TimeoutExpired:
                    run_log.write_text("TIMEOUT after 120s\n")
                    record.update({"pass": False, "reason": "timeout"})
                runs.append(record)

    parser_test = HERE / "test_thag_parser.py"
    parser_record = {"ran": False, "pass": True, "skipped": True}
    parser_log = LOGS / "tracka-thag-parser.run.log"
    if parser_test.exists():
        parser_result = subprocess.run(
            [sys.executable, "-B", str(parser_test)],
            cwd=str(BUILD),
            capture_output=True,
            text=True,
            timeout=120,
        )
        parser_log.write_text(parser_result.stdout + parser_result.stderr)
        parser_record = {
            "ran": True,
            "pass": parser_result.returncode == 0,
            "returncode": parser_result.returncode,
            "log": str(parser_log),
        }
        try:
            parser_record["report"] = json.loads(parser_result.stdout)
        except Exception:
            parser_record["report_text"] = parser_result.stdout

    aggregate = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "provenance": provenance,
        "compilers": {
            name: {"path": str(path), "version": compiler_version(path)}
            for name, path in compilers
        },
        "limitations": [
            "OSCompareAndSwap is a native atomic CAS mock, not macOS _OSCompareAndSwap.",
            "vnode/uio/vfs calls are mocks; no XNU vnode, uio, or filesystem is touched.",
            "hangThread executes as a pthread, not as a real ThreadCall callback.",
            "The mock HangRecord size is not the real THAG wire record size.",
            "Mock fault injection cannot reproduce uncancellable XNU I/O or real scheduling.",
        ],
        "runs": runs,
        "thag_parser": parser_record,
    }
    all_pass = all(run.get("pass") for run in runs) and parser_record.get("pass", True)
    aggregate["pass"] = bool(all_pass)
    results_path = LOGS / "tracka-results.json"
    results_path.write_text(json.dumps(aggregate, indent=2) + "\n")

    print(f"results: {results_path}")
    for run in runs:
        report = run.get("report", {})
        print(
            f"  {run['impl']:9s} {run['compiler']:5s} {run['variant']:10s} "
            f"compile={run['compile_returncode']} "
            f"checks={report.get('total', '?')} failed={report.get('failed', '?')} "
            f"pass={run.get('pass')}"
        )
    print(f"  thag-parser pass={parser_record.get('pass')} ran={parser_record.get('ran')}")
    print(f"overall pass={all_pass}")
    return 0 if all_pass else 1


if __name__ == "__main__":
    sys.exit(main())
