#!/usr/bin/env python3
"""Path-independent Track B build, test, sanitizer, and provenance runner."""

from __future__ import annotations

import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import sys


os.environ.setdefault("PYTHONDONTWRITEBYTECODE", "1")


ROOT = Path(__file__).resolve().parents[1]
INCLUDE = ROOT / "include"
SOURCES = [
    ROOT / "src" / "recordwire.cpp",
    ROOT / "src" / "snapshot_writer.cpp",
    ROOT / "tests" / "test_snapshot_writer.cpp",
]
BUILD = ROOT / ".build"
LOGS = ROOT / "logs"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_provenance() -> None:
    files = [
        ROOT / "include" / "recordwire.hpp",
        ROOT / "include" / "snapshot_writer.hpp",
        ROOT / "src" / "recordwire.cpp",
        ROOT / "src" / "snapshot_writer.cpp",
        ROOT / "tests" / "test_snapshot_writer.cpp",
    ]
    target = ROOT / "PROVENANCE-SHA256.txt"
    with target.open("w", encoding="ascii") as stream:
        stream.write("# Generated by tests/run_tests.py using Python hashlib.sha256\n")
        for path in files:
            stream.write(f"{sha256(path)}  {path.relative_to(ROOT).as_posix()}\n")


def run_variant(log, compiler: str, label: str, extra: list[str]) -> bool:
    build_dir = BUILD / label
    build_dir.mkdir(parents=True, exist_ok=True)
    binary = build_dir / "test_snapshot_writer"
    command = [
        compiler,
        "-std=c++17",
        "-Wall",
        "-Wextra",
        "-Wpedantic",
        "-Werror",
        "-DGA37_TEST_FAULTS",
        "-I",
        str(INCLUDE),
        *extra,
        *(str(path) for path in SOURCES),
        "-o",
        str(binary),
    ]
    log.write(f"\n$ {' '.join(command)}\n")
    log.flush()
    built = subprocess.run(command, cwd=ROOT, text=True, stdout=log, stderr=log)
    if built.returncode != 0:
        log.write(f"BUILD FAIL {label}: {built.returncode}\n")
        return False
    env = os.environ.copy()
    if "sanitize" in label:
        env.setdefault("ASAN_OPTIONS", "detect_leaks=0:halt_on_error=1")
        env.setdefault("UBSAN_OPTIONS", "halt_on_error=1:print_stacktrace=1")
    log.write(f"$ {binary}\n")
    log.flush()
    tested = subprocess.run([str(binary)], cwd=ROOT, env=env, text=True,
                            stdout=log, stderr=log)
    log.write(f"TEST {'PASS' if tested.returncode == 0 else 'FAIL'} {label}\n")
    return tested.returncode == 0


def main() -> int:
    BUILD.mkdir(parents=True, exist_ok=True)
    LOGS.mkdir(parents=True, exist_ok=True)
    write_provenance()
    log_path = LOGS / "latest-matrix.log"
    previous_log = LOGS / "pre-relocation-latest-matrix.log"
    if log_path.exists() and not previous_log.exists():
        shutil.copyfile(log_path, previous_log)
    variants = [
        ("clang++", "clang-debug", ["-O0", "-g"]),
        ("clang++", "clang-release", ["-O2"]),
        ("clang++", "clang-asan", ["-O1", "-g", "-fsanitize=address",
                                     "-fno-omit-frame-pointer"]),
        ("clang++", "clang-ubsan", ["-O1", "-g", "-fsanitize=undefined",
                                      "-fno-omit-frame-pointer"]),
    ]
    gcc = shutil.which("g++")
    if gcc is None:
        nix_gcc = sorted(Path("/nix/store").glob("*gcc-wrapper-*/bin/g++"))
        if nix_gcc:
            gcc = str(nix_gcc[-1])
    if gcc:
        variants.extend([
            (gcc, "gcc-debug", ["-O0", "-g"]),
            (gcc, "gcc-release", ["-O2"]),
            (gcc, "gcc-asan", ["-O1", "-g", "-fsanitize=address",
                                "-fno-omit-frame-pointer"]),
            (gcc, "gcc-ubsan", ["-O1", "-g", "-fsanitize=undefined",
                                 "-fno-omit-frame-pointer"]),
        ])
    else:
        variants.append(("", "gcc-unavailable", []))

    results = []
    with log_path.open("w", encoding="utf-8") as log:
        log.write(f"ROOT={ROOT}\n")
        for compiler, label, flags in variants:
            if not compiler:
                log.write("SKIP gcc variants: g++ not found on this host\n")
                results.append(True)
                continue
            results.append(run_variant(log, compiler, label, flags))
        log.write(f"SUMMARY {'PASS' if all(results) else 'FAIL'}\n")
    print(log_path)
    return 0 if all(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
