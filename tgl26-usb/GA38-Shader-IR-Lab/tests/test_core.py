class ByteLaneOracles(unittest.TestCase):
    def test_source_nonunit_stride_literal_oracle(self):
        o = {'kind': 'RD', 'reg': {'rn': 'r', 'r': 2, 'sr': 1}, 'type': 'f',
             'rgn': {'v': 4, 'w': 4, 'h': 2}}
        a = operand_access(o, 'READ', 8, 0, 'all instruction channels execute', 'SRC0')
        self.assertEqual([e['byte_start'] for e in a.elements], [68, 76, 84, 92, 84, 92, 100, 108])
        self.assertEqual([e['byte_end'] for e in a.elements], [72, 80, 88, 96, 88, 96, 104, 112])

    def test_dest_halfword_and_channel_offset_literal_oracle(self):
        o = {'kind': 'RD', 'reg': {'rn': 'r', 'r': 3, 'sr': 2}, 'type': 'uw', 'rgn': {'h': 2}}
        a = operand_access(o, 'WRITE', 4, 16, 'mask active', 'DST')
        self.assertEqual([e['byte_start'] for e in a.elements], [100, 104, 108, 112])
        self.assertEqual([e['lane'] for e in a.elements], [16, 17, 18, 19])

    def test_scalar_broadcast_has_one_physical_element(self):
        o = {'kind': 'RD', 'reg': {'rn': 'r', 'r': 1, 'sr': 3}, 'type': 'f', 'rgn': {'v': 0, 'w': 1, 'h': 0}}
        a = operand_access(o, 'READ', 32, 0, 'mask active', 'SRC0')
        self.assertEqual({(e['byte_start'], e['byte_end']) for e in a.elements}, {(44, 48)})
        self.assertEqual(len(a.elements), 32)

    def test_lane_labels_are_not_independence_proof(self):
        a = {'mode': 'WRITE', 'file': 'GRF', 'state': 'CONDITIONAL',
             'elements': [{'byte_start': 0, 'byte_end': 4, 'lane': 0}]}
        b = {'mode': 'READ', 'file': 'GRF', 'state': 'CONDITIONAL',
             'elements': [{'byte_start': 0, 'byte_end': 4, 'lane': 16}]}
        self.assertEqual(overlap(a, b)['relation'], 'MAY_DEPEND')

    def test_partial_register_overlap_is_dependency(self):
        a = {'file': 'GRF', 'state': 'KNOWN', 'elements': [{'byte_start': 32, 'byte_end': 36, 'lane': 0}]}
        b = {'file': 'GRF', 'state': 'KNOWN', 'elements': [{'byte_start': 34, 'byte_end': 36, 'lane': 0}]}
        self.assertEqual(overlap(a, b)['relation'], 'MUST_DEPEND')
        self.assertEqual(overlap(a, b)['overlap_bytes'][0]['byte_start'], 34)

    def test_unknown_is_not_none(self):
        a = asdict(symbolic('WRITE', 'ANY', 'TEST', 'unknown register file', 'unknown'))
        b = {'file': 'GRF', 'state': 'KNOWN', 'elements': [{'byte_start': 4092, 'byte_end': 4096, 'lane': 31}]}
        self.assertEqual(overlap(a, b)['relation'], 'UNKNOWN')
        a['state'], a['elements'] = 'NONE', []
        self.assertEqual(overlap(a, b)['relation'], 'INDEPENDENT_PROVEN')

    def test_nf_no_guessed_physical_width(self):
        o = {'kind': 'RD', 'reg': {'rn': 'acc'}, 'type': 'nf', 'rgn': {'h': 1}}
        a = operand_access(o, 'WRITE', 8, 0, 'all channels', 'DST')
        self.assertEqual(a.state, 'UNKNOWN')
        self.assertIsNone(a.elements)
        self.assertEqual(a.file, 'ACC')

    def test_register_integer_overflow_rejected(self):
        o = {'kind': 'RD', 'reg': {'rn': 'r', 'r': 1 << 100}, 'type': 'f', 'rgn': {'h': 1}}
        with self.assertRaisesRegex(Rejected, 'r'):
            operand_access(o, 'WRITE', 8, 0, 'all', 'DST')

    def test_unknown_type_and_indirection_are_symbolic(self):
        for o in [{'kind': 'RI', 'reg': {'rn': 'r'}, 'type': 'f'},
                  {'kind': 'RD', 'reg': {'rn': 'r'}, 'type': 'future', 'rgn': {'h': 1}}]:
            a = operand_access(o, 'READ', 8, 0, 'mask', 'SRC0')
            self.assertEqual(a.state, 'UNKNOWN')
            self.assertIsNone(a.elements)

    def test_random_interval_symmetry_and_monotonicity(self):
        rng = random.Random(0x38)
        for _ in range(500):
            lo, size, lo2, size2 = [rng.randrange(1, 64) for _ in range(4)]
            a = {'file': 'GRF', 'state': 'KNOWN', 'elements': [{'byte_start': lo, 'byte_end': lo + size, 'lane': 0}]}
            b = {'file': 'GRF', 'state': 'KNOWN', 'elements': [{'byte_start': lo2, 'byte_end': lo2 + size2, 'lane': 0}]}
            self.assertEqual(overlap(a, b)['relation'], overlap(b, a)['relation'])
            # Widening either footprint cannot turn a dependence into independence.
            if overlap(a, b)['relation'] != 'INDEPENDENT_PROVEN':
                a['elements'][0].update(byte_start=0, byte_end=256)
                self.assertNotEqual(overlap(a, b)['relation'], 'INDEPENDENT_PROVEN')


class RawAndDescriptorOracles(unittest.TestCase):
    def test_framing_native_compact_and_truncation(self):
        native = bytes(16)
        compact = (1 << 29).to_bytes(4, 'little') + bytes(4)
        self.assertEqual(frames(native + compact), [(0, 16), (16, 8)])
        for data, expected in [(native[:8], 'TRUNCATED_NATIVE'), (compact[:7], 'TRUNCATED_COMPACT')]:
            with self.assertRaises(Rejected) as ctx:
                frames(data)
            self.assertEqual(ctx.exception.code, expected)

    def test_descriptor_literal_fields(self):
        # Literal actual sampler SIMD8 desc 0x02420001, exdesc 0x42.
        self.assertEqual(bits(0x02420001, 28, 25), 1)
        self.assertEqual(bits(0x02420001, 24, 20), 4)
        self.assertEqual(bits(0x02420001, 18, 17), 1)
        self.assertEqual(bits(0x02420001, 7, 0), 1)
        self.assertEqual(bits(0x42, 9, 6), 1)
        self.assertEqual(bits(0x42, 3, 0), 2)

    def test_dynamic_descriptor_stays_unknown(self):
        f = immediate({'kind': 'RD', 'reg': {'rn': 'a'}})
        self.assertEqual(f['state'], 'UNKNOWN')
        self.assertIsNone(f['value'])

    def test_descriptor_overflow_and_negative_rejected(self):
        for n in [-1, 1 << 32, 1 << 100]:
            with self.assertRaises(Rejected):
                bits(n, 31, 0)

    def test_output_scope_rejected(self):
        for p in [ROOT.parent / 'GA32-ISA-Lab', Path('/tmp/opencode/ga38-escape')]:
            with self.assertRaises(Rejected):
                output_root(p)


class ActualProgramCoverage(unittest.TestCase):
    def test_serialized_ir_roundtrip_integrity(self):
        for path in sorted((RUN / 'ir/outputs').glob('*.json')):
            program = load(path)
            self.assertEqual(sha(validate_program(program)), program['program_sha256'])
            # Changing JSON key order cannot change a symbolic access set.
            reordered = json.loads(json.dumps(program, sort_keys=False))
            self.assertEqual(sha(validate_program(reordered)), program['program_sha256'])

    def test_full_raw_coverage_and_no_unknown_empty_arrays(self):
        counts = []
        for p in ['PS0', 'PS-KP1', 'PS-KP2', 'VS']:
            for side in ['source', 'candidate']:
                ir = load(RUN / f'ir/outputs/{p}-{side}.json')
                raw = (RUN / f'corpus/{side}/{p}.bin').read_bytes()
                self.assertEqual(b''.join(bytes.fromhex(n['raw_hex']) for n in ir['nodes']), raw)
                self.assertEqual(ir['program_sha256'], sha(raw))
                self.assertEqual([n['byte_range'] for n in ir['nodes']], [[o, o+s] for o, s in frames(raw)])
                self.assertEqual(sum(n['control_effects']['eot'] for n in ir['nodes']), 1)
                for n in ir['nodes']:
                    for a in n['register_access']['accesses']:
                        if a['state'] in {'UNKNOWN', 'INVALID'}:
                            self.assertIsNone(a['elements'])
                            self.assertTrue(a['symbolic_set'])
                        if a['state'] == 'NONE':
                            self.assertEqual(a['elements'], [])
                if side == 'source':
                    counts.append(len(ir['nodes']))
        self.assertEqual(counts, [11, 29, 15, 24])

    def test_twelve_layers_per_real_source_instruction(self):
        for p, count in [('PS0', 11), ('PS-KP1', 29), ('PS-KP2', 15), ('VS', 24)]:
            d = load(RUN / f'validator/outputs/{p}-comparison.json')
            self.assertEqual(len(d['findings']), 12 * count)
            self.assertEqual(len({(x['source_offset'], x['layer']) for x in d['findings']}), 12 * count)
            self.assertFalse(d['hardware_validated'])

    def test_mac_independent_implicit_access_oracle(self):
        for side in ['source', 'candidate']:
            d = load(RUN / f'ir/outputs/VS-{side}.json')
            n = next(n for n in d['nodes'] if n['byte_range'][0] == 0x20)
            self.assertEqual(n['opcode'], 'mac')
            self.assertTrue(any(a['mode'] == 'READ' and a['file'] == 'ACC' and a['role'] == 'MAC_IMPLICIT_ACC'
                                for a in n['register_access']['accesses']))

    def test_mapping_rejects_overlap_and_uncovered_target(self):
        s = load(RUN / 'ir/outputs/PS0-source.json')
        t = load(RUN / 'ir/outputs/PS0-candidate.json')
        for entries, code in [([{'source_offset': 0, 'target_byte_range': [0, 16]},
                         {'source_offset': 16, 'target_byte_range': [0, 16]}],
                        'MAPPING_OVERLAP'),
                        ([{'source_offset': 0, 'target_byte_range': [0, 16]}], 'MAPPING_INCOMPLETE')]:
            with self.assertRaises(Rejected) as ctx:
                validate_mapping(s, t, {'entries': entries, 'source_sha256': s['program_sha256'],
                                         'candidate_sha256': t['program_sha256']})
            self.assertEqual(ctx.exception.code, code)


