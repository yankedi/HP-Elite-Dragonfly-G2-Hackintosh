#!/usr/bin/env python3
"""Stage a private HP VESA first-boot candidate, never deploy to a device.

Starts from the validated reference prototype, adds the reviewed HP laptop
EC/USBX candidate and a private identity generated by the pinned macserial.
Boot success, USB port mapping and installer-media integration remain untested.
"""

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import secrets
import shutil
import subprocess
import tempfile
import uuid
import zipfile

from check_recovery_probe import ARCHIVE, ARCHIVE_SHA
from validate_efi import validate

ROOT = Path(__file__).resolve().parents[1]


def sha(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prototype", default="build/vesa-prototype")
    args = parser.parse_args()
    prototype = (ROOT / args.prototype).resolve(strict=True)
    if not prototype.is_relative_to(ROOT / "build"):
        raise ValueError("Use the local reference prototype in build/")
    source_report = json.loads((prototype / "report.json").read_text())
    for item in source_report["files"]:
        if sha(prototype / item["path"]) != item["sha256"]:
            raise ValueError("Reference prototype changed: " + item["path"])
    validate(prototype)
    if sha(ARCHIVE) != ARCHIVE_SHA:
        raise ValueError("Pinned OpenCore release differs")
    os.umask(0o077)
    base = ROOT / ".local/install-prep"
    base.mkdir(parents=True, exist_ok=True)
    directory = Path(tempfile.mkdtemp(prefix="hp-vesa-", dir=base))
    shutil.copytree(prototype / "EFI", directory / "EFI")
    shutil.copytree(prototype / "Licenses", directory / "Licenses")
    oc = directory / "EFI/OC"
    with zipfile.ZipFile(ARCHIVE) as archive:
        macserial = directory / "macserial"
        macserial.write_bytes(archive.read("Utilities/macserial/macserial.linux"))
        macserial.chmod(0o700)
        validator = directory / "ocvalidate"
        validator.write_bytes(archive.read("Utilities/ocvalidate/ocvalidate.linux"))
        validator.chmod(0o700)
    model = "MacBookPro16,2"
    result = subprocess.run([str(macserial), "--generate", "--model", model, "--num", "1"],
                            capture_output=True, text=True, check=True, timeout=20)
    # Never echo generated identity values into the conversation or public logs.
    pairs = re.findall(r"\b([A-Z0-9]{12})\s*\|\s*([A-Z0-9]{17})\b", result.stdout)
    if len(pairs) != 1:
        raise ValueError("Unexpected macserial output; identity was not applied")
    serial, mlb = pairs[0]
    rom = bytes([secrets.randbits(8) & 0xFC | 0x02]) + secrets.token_bytes(5)
    identity = {"SystemProductName": model, "SystemSerialNumber": serial,
                "MLB": mlb, "SystemUUID": str(uuid.uuid4()).upper(), "ROM": rom}
    identity_file = directory / "private-identity.plist"
    identity_file.write_bytes(plistlib.dumps(identity))
    config_file = oc / "config.plist"
    config = plistlib.loads(config_file.read_bytes())
    config["PlatformInfo"]["Generic"].update(identity)
    guid = "7C436110-AB2A-4BBB-A880-FE41995C9F82"
    config["NVRAM"]["Add"][guid]["prev-lang:kbd"] = b"en-US:0"
    source = ROOT / "acpi/SSDT-EC-USBX-HP.dsl"
    result = subprocess.run(["iasl", "-p", str(oc / "ACPI/SSDT-EC-USBX-HP"), str(source)],
                            capture_output=True, check=True, timeout=30)
    (directory / "ec-usbx-compile.log").write_bytes(result.stdout + result.stderr)
    config["ACPI"]["Add"].append({"Comment": "HP laptop fake EC + generic USBX; physical runtime untested",
                                 "Enabled": True, "Path": "SSDT-EC-USBX-HP.aml"})
    config_file.write_bytes(plistlib.dumps(config, sort_keys=False))
    result = subprocess.run([str(validator), str(config_file)], capture_output=True, timeout=20)
    (directory / "ocvalidate.log").write_bytes(result.stdout + result.stderr)
    if result.returncode:
        raise ValueError("Candidate failed matching OpenCore ocvalidate; inspect private log")
    validation = validate(directory)
    files = [{"path": str(path.relative_to(directory)), "sha256": sha(path)}
             for path in sorted((directory / "EFI").rglob("*")) if path.is_file()]
    blockers = ["No HP boot observation yet", "Complete physical USB map is not available",
                "Preserved Ventoy boot chain is not yet validated",
                "Full offline installer media generation/validation is pending",
                "CPU spoof and ACPI/memory quirks remain experimental on HP"]
    report = {"schema_version": 1, "created_at": datetime.now(timezone.utc).isoformat(),
              "status": "private_vesa_first_boot_candidate_unbooted", "deployment_ready": False,
              "prototype_report_sha256": sha(prototype / "report.json"), "ocvalidate_exit_code": 0,
              "opencore_version": "1.0.8", "opencore_archive_sha256": ARCHIVE_SHA,
              "macserial_sha256": sha(macserial), "private_identity_generated": True,
              "identity_values_in_public_report": False, "ec_usbx_source_sha256": sha(source),
              "static_validation": validation, "files": files, "remaining_limits": blockers,
              "physical_devices_written": False, "nvram_or_firmware_changed": False}
    (directory / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    (directory / "STATUS.txt").write_text("Private unbooted VESA candidate, not validated installation media.\n"
        "Do not publish the EFI/config.plist or private-identity.plist.\n" + "\n".join(blockers) + "\n")
    print(json.dumps({"candidate": str(directory.relative_to(ROOT)), "ocvalidate": 0,
                      "private_identity_generated": True, "deployment_ready": False}, indent=2))


if __name__ == "__main__":
    main()
